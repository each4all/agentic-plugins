const MARKER_LINE_RE = /^<!-- pipeline:(begin|end|extension) ([a-z][a-z0-9._-]*) -->$/;

function fenceOf(trimmed) {
  const m = /^(`{3,}|~{3,})/.exec(trimmed);
  return m ? m[1] : null;
}

/**
 * Parse the region markers of a Markdown file.
 *
 * Grammar (ADR-0066 Decision 4): a marker stands on its own line, outside any
 * code fence (marker text inside ``` or ~~~ is not a marker); each begin has
 * exactly one matching end; regions never nest; an id appears once per file.
 * Any other line outside a fence that starts with `<!-- pipeline:` is a broken
 * marker.
 *
 * @returns {{ regions: Array<{id, begin, end}>, extensions: Array<{id, line}>, errors: string[] }}
 *   `begin`/`end` are 0-based line indexes of the marker lines.
 */
export function parseRegions(text, file = '<text>') {
  const lines = text.split('\n');
  const regions = [];
  const extensions = [];
  const errors = [];
  const seen = new Set();
  let fence = null;
  let open = null;
  for (let i = 0; i < lines.length; i++) {
    const trimmed = lines[i].trim();
    const f = fenceOf(trimmed);
    if (fence) {
      if (f && f[0] === fence[0] && f.length >= fence.length && trimmed.slice(f.length).trim() === '') fence = null;
      continue;
    }
    if (f) {
      fence = f;
      continue;
    }
    if (!lines[i].includes('<!-- pipeline:')) continue;
    const m = MARKER_LINE_RE.exec(lines[i]);
    if (!m) {
      errors.push(`${file}:${i + 1}: broken pipeline marker (a marker stands alone on its line: <!-- pipeline:begin|end|extension <id> -->)`);
      continue;
    }
    const [, kind, id] = m;
    if (kind === 'extension') {
      if (open) errors.push(`${file}:${i + 1}: extension point ${id} inside region ${open.id}`);
      extensions.push({ id, line: i });
      continue;
    }
    if (kind === 'begin') {
      if (open) {
        errors.push(`${file}:${i + 1}: region ${id} begins inside region ${open.id} (regions never nest)`);
        continue;
      }
      if (seen.has(id)) errors.push(`${file}:${i + 1}: duplicate region id ${id}`);
      seen.add(id);
      open = { id, begin: i };
      continue;
    }
    // end
    if (!open) {
      errors.push(`${file}:${i + 1}: end of region ${id} without a begin`);
      continue;
    }
    if (open.id !== id) {
      errors.push(`${file}:${i + 1}: end of region ${id} while region ${open.id} is open`);
      continue;
    }
    regions.push({ id, begin: open.begin, end: i });
    open = null;
  }
  if (open) errors.push(`${file}:${open.begin + 1}: region ${open.id} has no end`);
  if (fence) errors.push(`${file}: unterminated code fence`);
  return { regions, extensions, errors };
}

/** The text between a region's markers (exclusive), as found in the file. */
export function regionBody(text, region) {
  const lines = text.split('\n');
  return lines.slice(region.begin + 1, region.end).join('\n');
}

/** Replace region bodies; `bodies` maps region id -> new body text. */
export function replaceRegionBodies(text, regions, bodies) {
  const lines = text.split('\n');
  const out = [];
  let cursor = 0;
  for (const region of [...regions].sort((a, b) => a.begin - b.begin)) {
    out.push(...lines.slice(cursor, region.begin + 1));
    const body = Object.hasOwn(bodies, region.id) ? bodies[region.id] : lines.slice(region.begin + 1, region.end).join('\n');
    if (body.length > 0) out.push(...body.split('\n'));
    cursor = region.end;
  }
  out.push(...lines.slice(cursor));
  return out.join('\n');
}

