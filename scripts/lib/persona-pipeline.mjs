// The persona pipeline engine (ADR-0066 Decision 4): the manifest, the
// ownership ledger, the generated-file notice, the region grammar and the
// region renderer. scripts/sync-persona-pipeline.mjs drives it; the tests in
// tests/persona-pipeline/ drive it on fixtures.
//
// Nothing here runs inside a plugin. It is development tooling, like
// scripts/sync-companion-bundles.mjs: it reads persona-pipeline/ and writes the
// generated copies each persona plugin carries.

import { readFileSync } from 'node:fs';
import { extname, isAbsolute, normalize, posix } from 'node:path';

export const MANIFEST_SCHEMA = 'persona-pipeline-manifest-1.0';
export const OWNED_SCHEMA = 'persona-pipeline-owned-1.0';
export const WRITE_COMMAND = 'npm run sync:persona-pipeline -- --write';
export const NOTICE_MARK = 'GENERATED by persona-pipeline';

const ID_RE = /^[a-z][a-z0-9._-]*$/;
const PERSONA_RE = /^[a-z][a-z0-9-]*$/;
const FIELD_RE = /^[a-z_][a-z0-9_]*(\.[a-z_][a-z0-9_]*)*$/;
const CAPABILITIES = Object.freeze(['dispatch_target', 'commit_surface', 'legacy_homes', 'profile_presets']);
const CONTEXTS = new Set(['shell', 'text', 'markdown']);

export class PipelineError extends Error {
  constructor(message) {
    super(message);
    this.name = 'PipelineError';
  }
}

export { CAPABILITIES };

// ---------------------------------------------------------------------------
// Manifest
// ---------------------------------------------------------------------------

function fail(where, message) {
  throw new PipelineError(`${where}: ${message}`);
}

function isPlainObject(value) {
  return value !== null && typeof value === 'object' && !Array.isArray(value);
}

function stringList(value, where, { pattern, allowEmpty = true } = {}) {
  if (!Array.isArray(value)) fail(where, 'must be a list');
  if (!allowEmpty && value.length === 0) fail(where, 'must not be empty');
  const seen = new Set();
  for (const item of value) {
    if (typeof item !== 'string' || item.length === 0) fail(where, 'entries must be non-empty strings');
    if (pattern && !pattern.test(item)) fail(where, `invalid entry ${JSON.stringify(item)}`);
    if (seen.has(item)) fail(where, `duplicate entry ${JSON.stringify(item)}`);
    seen.add(item);
  }
  return value;
}

function onlyKeys(obj, allowed, where) {
  for (const key of Object.keys(obj)) {
    if (!allowed.includes(key)) fail(where, `unknown key ${JSON.stringify(key)}`);
  }
}

/**
 * A plugin-relative path the pipeline may write: relative, normalized,
 * forward-slashed, no `..` segment, no empty segment. Returns the reason it is
 * not one, or null.
 */
export function unsafePathReason(path) {
  if (typeof path !== 'string' || path.length === 0) return 'empty path';
  if (path.includes('\\')) return 'backslash in path';
  if (isAbsolute(path) || path.startsWith('/')) return 'absolute path';
  if (path.split('/').some((seg) => seg === '..')) return 'path traversal (..)';
  if (path.split('/').some((seg) => seg === '' || seg === '.')) return 'non-normalized path';
  if (posix.normalize(path) !== path || normalize(path).split('\\').join('/') !== path) {
    return 'non-normalized path';
  }
  return null;
}

/**
 * Validate a parsed manifest object. Throws PipelineError naming the first
 * problem; returns the manifest unchanged.
 */
export function validateManifest(manifest) {
  const where = 'manifest';
  if (!isPlainObject(manifest)) fail(where, 'is not an object');
  onlyKeys(manifest, ['schema', 'personas', 'units', 'regions', 'extension_points'], where);
  if (manifest.schema !== MANIFEST_SCHEMA) {
    fail(where, `schema is ${JSON.stringify(manifest.schema)}, expected ${JSON.stringify(MANIFEST_SCHEMA)}`);
  }
  const personas = stringList(manifest.personas, `${where}.personas`, { pattern: PERSONA_RE, allowEmpty: false });
  const personaSet = new Set(personas);
  const enrolment = (list, w) => {
    stringList(list, w, { pattern: PERSONA_RE, allowEmpty: false });
    for (const p of list) if (!personaSet.has(p)) fail(w, `persona ${JSON.stringify(p)} is not in manifest.personas`);
  };

  if (!Array.isArray(manifest.units)) fail(`${where}.units`, 'must be a list');
  const unitIds = new Set();
  for (const [i, unit] of manifest.units.entries()) {
    const w = `${where}.units[${i}]`;
    if (!isPlainObject(unit)) fail(w, 'is not an object');
    onlyKeys(unit, ['id', 'source', 'dest', 'personas', 'requires', 'off_only', 'on_only'], w);
    if (typeof unit.id !== 'string' || !ID_RE.test(unit.id)) fail(w, 'id must match [a-z][a-z0-9._-]*');
    if (unitIds.has(unit.id)) fail(w, `duplicate unit id ${JSON.stringify(unit.id)}`);
    unitIds.add(unit.id);
    for (const key of ['source', 'dest']) {
      const reason = unsafePathReason(unit[key]);
      if (reason) fail(`${w}.${key}`, `${reason}: ${JSON.stringify(unit[key])}`);
    }
    enrolment(unit.personas, `${w}.personas`);
    stringList(unit.requires ?? [], `${w}.requires`);
    stringList(unit.off_only ?? [], `${w}.off_only`);
    for (const cap of unit.off_only ?? []) {
      if (!CAPABILITIES.includes(cap)) fail(`${w}.off_only`, `unknown capability ${JSON.stringify(cap)}`);
    }
    stringList(unit.on_only ?? [], `${w}.on_only`);
    for (const cap of unit.on_only ?? []) {
      if (!CAPABILITIES.includes(cap)) fail(`${w}.on_only`, `unknown capability ${JSON.stringify(cap)}`);
      if ((unit.off_only ?? []).includes(cap)) fail(`${w}.on_only`, `${cap} is also in off_only`);
    }
  }

  if (!Array.isArray(manifest.regions)) fail(`${where}.regions`, 'must be a list');
  const regionKeys = new Set();
  for (const [i, region] of manifest.regions.entries()) {
    const w = `${where}.regions[${i}]`;
    if (!isPlainObject(region)) fail(w, 'is not an object');
    onlyKeys(region, ['id', 'template', 'dest', 'personas', 'substitutions', 'when'], w);
    if (typeof region.id !== 'string' || !ID_RE.test(region.id)) fail(w, 'id must match [a-z][a-z0-9._-]*');
    for (const key of ['template', 'dest']) {
      const reason = unsafePathReason(region[key]);
      if (reason) fail(`${w}.${key}`, `${reason}: ${JSON.stringify(region[key])}`);
    }
    const key = `${region.dest}\0${region.id}`;
    if (regionKeys.has(key)) fail(w, `region ${JSON.stringify(region.id)} is declared twice for ${region.dest}`);
    regionKeys.add(key);
    enrolment(region.personas, `${w}.personas`);
    // A variant (PC2a3 DD2): which personas the region is enrolled for follows
    // a declared value; the generator checks the enrollment against it.
    if (Object.hasOwn(region, 'when')) {
      const ww = `${w}.when`;
      if (!isPlainObject(region.when)) fail(ww, 'is not an object');
      onlyKeys(region.when, ['field', 'equals'], ww);
      if (typeof region.when.field !== 'string' || !FIELD_RE.test(region.when.field)) fail(ww, 'field must be a dotted declaration path');
      if (!['string', 'number', 'boolean'].includes(typeof region.when.equals)) fail(ww, 'equals must be a string, a number or a boolean');
    }
    const subs = region.substitutions ?? {};
    if (!isPlainObject(subs)) fail(`${w}.substitutions`, 'must be an object');
    for (const [name, sub] of Object.entries(subs)) {
      const sw = `${w}.substitutions.${name}`;
      if (!/^[a-z][a-z0-9_]*$/.test(name)) fail(sw, 'invalid placeholder name');
      if (!isPlainObject(sub)) fail(sw, 'is not an object');
      onlyKeys(sub, ['field', 'value', 'context'], sw);
      // A substitution reads a declaration field, or carries a literal the
      // manifest fixes for this region (the verb a shared block runs for).
      if (Object.hasOwn(sub, 'field') === Object.hasOwn(sub, 'value')) fail(sw, 'needs exactly one of field and value');
      if (Object.hasOwn(sub, 'field') && (typeof sub.field !== 'string' || !FIELD_RE.test(sub.field))) {
        fail(sw, 'field must be a dotted declaration path');
      }
      if (Object.hasOwn(sub, 'value') && (typeof sub.value !== 'string' || sub.value.length === 0)) {
        fail(sw, 'value must be a non-empty string');
      }
      if (!CONTEXTS.has(sub.context)) fail(sw, `context must be one of ${[...CONTEXTS].join(', ')}`);
    }
  }

  // An extension slot (PC2a3 DD6): owned by `personas`, bounded on both sides
  // by two regions of the same file — the end of `after` and the begin of
  // `before`, each enrolled for every owner, `after` first in the canonical
  // order — and holding `min` to `max` markers.
  if (!Array.isArray(manifest.extension_points)) fail(`${where}.extension_points`, 'must be a list');
  const extKeys = new Set();
  for (const [i, ext] of manifest.extension_points.entries()) {
    const w = `${where}.extension_points[${i}]`;
    if (!isPlainObject(ext)) fail(w, 'is not an object');
    onlyKeys(ext, ['id', 'dest', 'personas', 'after', 'before', 'min', 'max'], w);
    if (typeof ext.id !== 'string' || !ID_RE.test(ext.id)) fail(w, 'id must match [a-z][a-z0-9._-]*');
    const reason = unsafePathReason(ext.dest);
    if (reason) fail(`${w}.dest`, `${reason}: ${JSON.stringify(ext.dest)}`);
    enrolment(ext.personas, `${w}.personas`);
    if (!Number.isInteger(ext.min) || ext.min < 0) fail(`${w}.min`, 'must be an integer >= 0');
    if (!Number.isInteger(ext.max) || ext.max < 1) fail(`${w}.max`, 'must be an integer >= 1');
    if (ext.min > ext.max) fail(w, `min ${ext.min} is greater than max ${ext.max}`);
    for (const bound of ['after', 'before']) {
      if (typeof ext[bound] !== 'string' || !ID_RE.test(ext[bound])) fail(`${w}.${bound}`, 'must be a region id');
      if (!manifest.regions.some((r) => r.dest === ext.dest && r.id === ext[bound])) {
        fail(`${w}.${bound}`, `names no region of ${ext.dest}: ${JSON.stringify(ext[bound])}`);
      }
    }
    for (const persona of ext.personas) {
      const order = canonicalOrder(manifest, ext.dest, persona);
      for (const bound of ['after', 'before']) {
        if (!order.includes(ext[bound])) fail(`${w}.${bound}`, `region ${ext[bound]} is not enrolled for ${persona} in ${ext.dest}`);
      }
      if (order.indexOf(ext.after) >= order.indexOf(ext.before)) {
        fail(w, `after (${ext.after}) does not come before before (${ext.before}) in ${ext.dest} for ${persona}`);
      }
    }
    const key = `${ext.dest}\0${ext.id}`;
    if (extKeys.has(key)) fail(w, `extension point ${JSON.stringify(ext.id)} is declared twice for ${ext.dest}`);
    extKeys.add(key);
  }
  return manifest;
}

/** The regions a file holds for one persona, in the manifest's (canonical) order. */
export function canonicalOrder(manifest, dest, persona) {
  return manifest.regions.filter((r) => r.dest === dest && r.personas.includes(persona)).map((r) => r.id);
}

function declaredValue(declaration, field) {
  let cur = declaration;
  for (const part of field.split('.')) {
    if (!isPlainObject(cur) || !Object.hasOwn(cur, part)) return undefined;
    cur = cur[part];
  }
  return cur;
}

/**
 * The variant rule (PC2a3 DD2): a region carrying `when: {field, equals}` is
 * enrolled for exactly the personas whose declaration holds `field` with the
 * same JSON type and value as `equals` (false, "false" and null all differ). A
 * declaration without the field (an older format) is never enrolled in it and
 * is not counted against it. Returns failure messages for one persona.
 */
export function variantEnrolmentFailures({ persona, declaration, regions, where = `plugins/${persona}/persona.json` }) {
  const failures = [];
  for (const region of regions) {
    if (!region.when) continue;
    const { field, equals } = region.when;
    const value = declaredValue(declaration, field);
    const enrolled = region.personas.includes(persona);
    const at = `region ${region.id} (${region.dest})`;
    if (value === undefined) {
      if (enrolled) failures.push(`${where}: enrolled in ${at}, whose variant reads ${field}, which the declaration lacks`);
    } else if (value === equals && !enrolled) {
      failures.push(`${where}: declares ${field} = ${JSON.stringify(value)}, so ${at} must enrol it (when ${field} is ${JSON.stringify(equals)})`);
    } else if (value !== equals && enrolled) {
      failures.push(`${where}: enrolled in ${at}, but declares ${field} = ${JSON.stringify(value)}, not ${JSON.stringify(equals)}`);
    }
  }
  return failures;
}

export function readJsonFile(path, label) {
  let text;
  try {
    text = readFileSync(path, 'utf8');
  } catch (err) {
    throw new PipelineError(`${label}: cannot read ${path} (${err.code ?? err.message})`);
  }
  try {
    return JSON.parse(text);
  } catch (err) {
    throw new PipelineError(`${label}: ${path} is not valid JSON (${err.message})`);
  }
}

/** The personas a whole-file unit is generated into, by its dest. */
export function personasFor(manifest, dest) {
  const unit = manifest.units.find((u) => u.dest === dest);
  if (!unit) throw new PipelineError(`no unit generates ${dest}`);
  return [...unit.personas];
}

