/**
 * The notice lines for a generated file, or null when its format carries none
 * (JSON: the manifest and the ledger record its provenance).
 */
export function noticeLines(sourceRel, dest) {
  const ext = extname(dest);
  const body = [
    `${NOTICE_MARK} — do not edit this copy.`,
    `Source: ${sourceRel}. Edit the source, then run`,
    `\`${WRITE_COMMAND}\` (ADR-0066).`,
  ];
  if (ext === '.mjs' || ext === '.js' || ext === '.cjs') return body.map((l) => `// ${l}`);
  if (ext === '.sh') return body.map((l) => `# ${l}`);
  if (ext === '.md') return [`<!-- ${body.join('\n     ')} -->`];
  if (ext === '.json') return null;
  throw new PipelineError(`no notice format for ${dest} (extension ${ext || 'none'})`);
}

/** Insert the notice: after a shebang in a script, after frontmatter in Markdown. */
export function withNotice(content, sourceRel, dest) {
  const lines = noticeLines(sourceRel, dest);
  if (lines === null) return content;
  const block = `${lines.join('\n')}\n`;
  if (content.startsWith('#!')) {
    const nl = content.indexOf('\n');
    if (nl === -1) return `${content}\n${block}`;
    return `${content.slice(0, nl + 1)}${block}${content.slice(nl + 1)}`;
  }
  if (extname(dest) === '.md' && content.startsWith('---\n')) {
    const end = content.indexOf('\n---\n', 4);
    if (end !== -1) {
      const cut = end + '\n---\n'.length;
      return `${content.slice(0, cut)}${block}${content.slice(cut)}`;
    }
  }
  return `${block}${content}`;
}

/** Whether a file's text carries a persona-pipeline notice near its top. */
export function carriesNotice(text) {
  return text.split('\n', 8).some((line) => line.includes(NOTICE_MARK));
}

