/** A shell-safe single-quoted literal. A newline is refused, never spliced. */
export function shellQuote(value) {
  if (typeof value !== 'string') throw new PipelineError(`shell substitution needs a string, got ${typeof value}`);
  if (/[\n\r\0]/.test(value)) throw new PipelineError('shell substitution refuses a value with a newline or NUL');
  return `'${value.split("'").join("'\\''")}'`;
}

function lookupField(declaration, field) {
  let cur = declaration;
  for (const part of field.split('.')) {
    if (!isPlainObject(cur) || !Object.hasOwn(cur, part)) return undefined;
    cur = cur[part];
  }
  return cur;
}

/**
 * The fields a template may read besides the declaration's own: values the
 * pipeline derives from the declaration, the way the runtime derives its
 * state directory and command prefix from the name (ADR-0066 Decision 2).
 * They sit under `derived`, a key the declaration schema does not allow, so
 * they never shadow a declared field.
 *
 *   - `root_env`: the persona's plugin-root variable, from its name.
 *   - `skill_privacy_spec`: `peer.privacy_spec` as a skill cites it — relative
 *     to a skill's own directory (`core/skills/<skill>/`), the same path from
 *     every skill (PC2a3 T7). Absent when the declaration has no spec, so a
 *     template that reads it fails to render rather than citing nothing.
 *   - `shared_privacy_spec`: the same spec as a shared reference cites it,
 *     relative to `core/skills/_shared/references/` (PC2a4). Absent without a
 *     spec.
 *   - `brief_file`: the file the investigate brief is saved as, its default
 *     profile with `-` → `_` plus `.md` (`business-brief` →
 *     `business_brief.md`); the generator checks that the declared
 *     `artifact` names that same file (PC2a4).
 *   - `output_root_env`: the variable that overrides where that brief is
 *     saved, `<NAME>_OUTPUT_ROOT`, from the name (PC2a4).
 *   Both are absent without `verbs.investigate.default_profile`. A declared
 *   `verbs.investigate.brief_file` / `output_root_env` wins over the
 *   derivation (PC3 U7: engineer's default profile is analysis, while its
 *   brief comes from the cited-brief profile as research_brief.md under
 *   RESEARCH_OUTPUT_ROOT).
 *   - `investigate_launched`, `investigate_synthesis`: what the investigate
 *     note's launched and synthesis headings name. With one declared profile,
 *     the ensemble type and the profile (founder: research-scan,
 *     business-brief); with several, whose point type differs by profile,
 *     `investigate (profile=<profile>)` for both, as critique's headings
 *     (PC3 U7, engineer). Absent without `verbs.investigate.profiles`.
 *   - `ensemble_skip_cause`, `ensemble_skip_label`: why a verb's ensemble
 *     never launched, as the finalize note states it. With a peer policy
 *     (`peer`) the privacy gate is what keeps a verb local-only; without one
 *     (engineer, which has no privacy gate) the verb simply ran local-only
 *     (PC3 U7).
 *   - `profile_env`: the variable the decide resolver reads the L4 profile
 *     from, `AGENTIC_<NAME>_PROFILE`, from the name as `lib/persona.mjs`
 *     `profileEnvVar` derives it; the resolver reads it only with the
 *     `profile_presets` capability on, and a template cites it only there
 *     (PC2a4).
 */
export function derivedFields(declaration) {
  const name = declaration?.name;
  if (typeof name !== 'string' || !/^[a-z][a-z0-9-]*$/.test(name)) return {};
  const upper = name.toUpperCase().split('-').join('_');
  const derived = { root_env: `AGENTIC_${upper}_ROOT`, profile_env: `AGENTIC_${upper}_PROFILE` };
  const gated = declaration?.peer !== undefined;
  derived.ensemble_skip_cause = gated ? 'the privacy gate kept the verb local-only, so no dispatch ran' : 'the verb ran local-only, so no dispatch ran';
  derived.ensemble_skip_label = gated ? 'privacy gate' : 'local-only';
  const spec = declaration?.peer?.privacy_spec;
  if (typeof spec === 'string' && spec.length > 0) {
    derived.skill_privacy_spec = `../${posix.relative('core/skills', spec)}`;
    derived.shared_privacy_spec = posix.relative('core/skills/_shared/references', spec);
  }
  const investigate = declaration?.verbs?.investigate;
  const profile = investigate?.default_profile;
  if (typeof profile === 'string' && profile.length > 0) {
    derived.brief_file = typeof investigate.brief_file === 'string' ? investigate.brief_file : `${profile.split('-').join('_')}.md`;
    derived.output_root_env = typeof investigate.output_root_env === 'string' ? investigate.output_root_env : `${upper}_OUTPUT_ROOT`;
  }
  const profiles = investigate?.profiles;
  if (Array.isArray(profiles) && profiles.length === 1) {
    if (typeof investigate.ensemble_type === 'string') derived.investigate_launched = investigate.ensemble_type;
    derived.investigate_synthesis = profiles[0];
  } else if (Array.isArray(profiles) && profiles.length > 1) {
    derived.investigate_launched = 'investigate (profile=<profile>)';
    derived.investigate_synthesis = 'investigate (profile=<profile>)';
  }
  return derived;
}

/** The declaration as templates read it: the declaration plus `derived`. */
export function renderingDeclaration(declaration) {
  return { ...declaration, derived: derivedFields(declaration) };
}

const SHELL_INFO = new Set(['bash', 'sh', 'zsh', 'shell']);

/**
 * Where each `{{…}}` of a template sits (ADR-0066 Decision 4, placement).
 * Returns one entry per occurrence, in order: `{ name, where }`, where `where`
 * is `prose` (outside any fence), `fence` (a fence that is not shell),
 * `word` (a shell fence, unquoted: the only place a single-quoted literal
 * means what it says), or `shell-<state>` for every other shell position —
 * `single`, `ansi` (inside `$'…'`, where `\\'` does not end the string),
 * `double`, `param` (inside `${…}`), `arith` (inside `$((…))` or `((…))`,
 * which expands a command substitution in it), `backtick`, `comment`,
 * `heredoc` (any delimiter; an unparsable one makes the rest of the block a
 * heredoc), `escaped` (right after a backslash, which would escape the
 * literal's opening quote). A command substitution `$(…)` opens a fresh
 * unquoted context, even inside double quotes, as the shell does. A
 * placeholder never spans lines.
 */
export function placeholderPlacements(template) {
  const out = [];
  const lines = template.split('\n');
  let fence = null; // { mark, shell }
  let heredocs = []; // queued { delim, strip }; delim null: unparsable, the rest of the block
  let stack = null; // shell lexer state inside a shell fence, carried across lines
  const record = (line, at, where) => {
    const close = line.indexOf('}}', at + 2);
    const name = (close === -1 ? line.slice(at + 2) : line.slice(at + 2, close)).trim();
    out.push({ name, where });
    return close === -1 ? line.length : close + 2;
  };
  const proseLine = (line, where) => {
    let at = line.indexOf('{{');
    while (at !== -1) {
      const next = record(line, at, where);
      at = line.indexOf('{{', next);
    }
  };
  for (const line of lines) {
    const trimmed = line.trim();
    const f = /^(`{3,}|~{3,})(.*)$/.exec(trimmed);
    if (!fence) {
      if (f) {
        const info = f[2].trim().split(/\s+/)[0].toLowerCase();
        fence = { mark: f[1], shell: SHELL_INFO.has(info) };
        stack = [{ kind: 'code', depth: 0 }];
        heredocs = [];
        continue;
      }
      proseLine(line, 'prose');
      continue;
    }
    if (f && f[1][0] === fence.mark[0] && f[1].length >= fence.mark.length && f[2].trim() === '') {
      fence = null;
      continue;
    }
    if (!fence.shell) {
      proseLine(line, 'fence');
      continue;
    }
    if (heredocs.length > 0) {
      const h = heredocs[0];
      const body = h.strip ? line.replace(/^\t+/, '') : line;
      if (h.delim !== null && body === h.delim) heredocs.shift();
      else proseLine(line, 'shell-heredoc');
      continue;
    }
    const top = () => stack[stack.length - 1];
    for (let i = 0; i < line.length;) {
      const st = top();
      const c = line[i];
      if (line.startsWith('{{', i)) {
        i = record(line, i, st.kind === 'code' ? 'word' : `shell-${st.kind}`);
        continue;
      }
      if (st.kind === 'single') {
        if (c === "'") stack.pop();
        i++;
        continue;
      }
      if (c === '\\' && line.startsWith('{{', i + 1)) {
        i = record(line, i + 1, 'shell-escaped');
        continue;
      }
      if (st.kind === 'ansi') {
        if (c === '\\') i += 2;
        else { if (c === "'") stack.pop(); i++; }
        continue;
      }
      if (c === '\\') { i += 2; continue; }
      if (st.kind === 'code' && c === '#' && (i === 0 || /[\s;&|(]/.test(line[i - 1]))) {
        proseLine(line.slice(i), 'shell-comment');
        break;
      }
      if (st.kind === 'arith') {
        if (c === '(') st.depth++;
        else if (c === ')') {
          if (st.depth > 0) st.depth--;
          else { stack.pop(); i += line[i + 1] === ')' ? 2 : 1; continue; }
        }
        i++;
        continue;
      }
      if (c === '$' && line[i + 1] === "'" && st.kind !== 'double') { stack.push({ kind: 'ansi' }); i += 2; continue; }
      if (c === '$' && line.startsWith('((', i + 1)) { stack.push({ kind: 'arith', depth: 0 }); i += 3; continue; }
      if (c === '$' && line[i + 1] === '(') { stack.push({ kind: 'code', depth: 0 }); i += 2; continue; }
      if (c === '$' && line[i + 1] === '{') { stack.push({ kind: 'param', depth: 0 }); i += 2; continue; }
      if (st.kind === 'param') {
        if (c === '{') st.depth++;
        else if (c === '}') { if (st.depth === 0) stack.pop(); else st.depth--; }
        else if (c === '"') stack.push({ kind: 'double' });
        else if (c === "'") stack.push({ kind: 'single' });
        i++;
        continue;
      }
      if (c === '`') {
        if (st.kind === 'backtick') stack.pop();
        else stack.push({ kind: 'backtick' });
        i++;
        continue;
      }
      if (st.kind === 'double') {
        if (c === '"') stack.pop();
        i++;
        continue;
      }
      // code or backtick
      if (c === "'") { stack.push({ kind: 'single' }); i++; continue; }
      if (c === '"') { stack.push({ kind: 'double' }); i++; continue; }
      if (c === '<' && line[i + 1] === '<' && line[i + 2] !== '<') {
        // A heredoc: its body starts on the next line. Any delimiter word is
        // read; one that cannot be read makes the rest of the block a heredoc.
        const h = /^<<(-?)[ \t]*(?:'([^']*)'|"([^"]*)"|((?:\\.|[^\s;&|<>()'"`])+))/.exec(line.slice(i));
        if (!h) { heredocs.push({ delim: null, strip: false }); i += 2; continue; }
        const delim = h[2] ?? h[3] ?? h[4].replace(/\\(.)/g, '$1');
        heredocs.push({ delim, strip: h[1] === '-' });
        i += h[0].length;
        continue;
      }
      if (c === '(' && line[i + 1] === '(') { stack.push({ kind: 'arith', depth: 0 }); i += 2; continue; }
      if (c === '(') st.depth = (st.depth ?? 0) + 1;
      else if (c === ')') {
        if (st.depth > 0) st.depth--;
        else if (stack.length > 1) stack.pop();
      }
      i++;
    }
  }
  return out;
}

const PLACEHOLDER_RE = /\{\{[ \t]*([^{}\n]*?)[ \t]*\}\}/g;
const BLOCK_OPEN_RE = /^\{\{([#^])capability ([a-z_]+)\}\}$/;
const BLOCK_CLOSE_RE = /^\{\{\/capability\}\}$/;

/**
 * Render a region template for one persona.
 *
 * Templates hold two constructs and nothing else:
 *   - `{{name}}` — a substitution the manifest declares for this region, with
 *     a field path into the declaration and a context (`shell`: emitted as a
 *     single-quoted literal; `text` / `markdown`: verbatim — a list of strings
 *     too, when the placeholder stands alone on its line: one line per item);
 *   - `{{#capability <cap>}}` … `{{/capability}}` (included when the persona has
 *     <cap> on) and `{{^capability <cap>}}` … `{{/capability}}` (when off), each
 *     marker alone on its line, never nested.
 * An unresolved or undeclared placeholder fails the render.
 */
export function renderTemplate(template, { declaration, substitutions = {}, label = 'template' }) {
  const lines = template.split('\n');
  const kept = [];
  let block = null;
  for (let i = 0; i < lines.length; i++) {
    const trimmed = lines[i].trim();
    const open = BLOCK_OPEN_RE.exec(trimmed);
    if (open) {
      if (block) throw new PipelineError(`${label}:${i + 1}: capability blocks never nest`);
      const [, sign, cap] = open;
      if (!CAPABILITIES.includes(cap)) throw new PipelineError(`${label}:${i + 1}: unknown capability ${cap}`);
      const on = declaration?.capabilities?.[cap];
      if (typeof on !== 'boolean') throw new PipelineError(`${label}:${i + 1}: the declaration does not set capabilities.${cap}`);
      block = { include: sign === '#' ? on : !on, line: i };
      continue;
    }
    if (BLOCK_CLOSE_RE.test(trimmed)) {
      if (!block) throw new PipelineError(`${label}:${i + 1}: {{/capability}} without an open block`);
      block = null;
      continue;
    }
    if (/\{\{\s*[#^/]/.test(trimmed)) {
      throw new PipelineError(`${label}:${i + 1}: a block marker stands alone on its line: {{#capability x}}, {{^capability x}}, {{/capability}}`);
    }
    if (block && !block.include) continue;
    kept.push(lines[i]);
  }
  if (block) throw new PipelineError(`${label}:${block.line + 1}: capability block has no {{/capability}}`);

  const text = kept.join('\n');
  // Placement (ADR-0066 Decision 4): a shell value is a single-quoted literal,
  // which means what it says only at an unquoted position of a shell block —
  // inside "…" a `$(…)` in the value would run. Text and markdown values are
  // verbatim, so they never enter a shell block at all.
  const placed = placeholderPlacements(text);
  const matched = [...text.matchAll(PLACEHOLDER_RE)].map((m) => m[1]);
  // Every replacement must be a placement the lexer read, in the same order:
  // a "{{" the lexer stepped over would otherwise be replaced unchecked.
  if (placed.length !== (text.split('{{').length - 1) || JSON.stringify(placed.map((p) => p.name)) !== JSON.stringify(matched)) {
    throw new PipelineError(`${label}: a placeholder the placement check could not read (a "{{" it stepped over, one spanning lines, or one left open)`);
  }
  for (const { name, where } of placed) {
    const sub = Object.hasOwn(substitutions, name) ? substitutions[name] : null;
    if (!sub) continue; // reported as unresolved below
    if (sub.context === 'shell' && where !== 'word') {
      throw new PipelineError(`${label}: {{${name}}} is a shell value but sits ${PLACE_TEXT[where] ?? where}; put it at an unquoted word position of a shell block`);
    }
    if (sub.context !== 'shell' && (where === 'word' || where.startsWith('shell-'))) {
      throw new PipelineError(`${label}: {{${name}}} is a ${sub.context} value inside a shell block; give it the shell context or move it to the prose`);
    }
  }
  const valueOf = (name) => {
    if (!Object.hasOwn(substitutions, name)) {
      throw new PipelineError(`${label}: unresolved placeholder {{${name}}} (not declared for this region)`);
    }
    const sub = substitutions[name];
    const value = Object.hasOwn(sub, 'value') ? sub.value : lookupField(declaration, sub.field);
    if (value === undefined || value === null) {
      throw new PipelineError(`${label}: unresolved placeholder {{${name}}}: the declaration has no ${sub.field}`);
    }
    // A list of lines (a phase note's artifact sections) is a markdown or text
    // value only: a shell value is one literal, never a list.
    const items = Array.isArray(value) ? value : [value];
    if (Array.isArray(value) && sub.context === 'shell') {
      throw new PipelineError(`${label}: placeholder {{${name}}}: ${sub.field ?? 'its value'} is a list, and a shell value is one literal`);
    }
    items.forEach((item, i) => {
      const what = Array.isArray(value) ? `${sub.field ?? 'its value'}[${i}]` : (sub.field ?? 'its value');
      if (typeof item !== 'string') {
        throw new PipelineError(`${label}: placeholder {{${name}}}: ${what} is not a string`);
      }
      if (Array.isArray(value) && /[\n\r\0]/.test(item)) {
        throw new PipelineError(`${label}: placeholder {{${name}}}: ${what} holds a line break; a list renders one line per item`);
      }
      if (item.includes('{{')) {
        throw new PipelineError(`${label}: placeholder {{${name}}}: the value holds "{{", which a later reader would take for a placeholder`);
      }
    });
    return { sub, value };
  };
  // A list stands alone on its line and renders one line per item, each with
  // that line's indentation (an empty item is a blank line).
  const LIST_LINE_RE = /^([ \t]*)\{\{[ \t]*([^{}\n]*?)[ \t]*\}\}[ \t]*$/;
  const expanded = text.split('\n').map((line) => {
    const m = LIST_LINE_RE.exec(line);
    if (!m) return line;
    const { value } = valueOf(m[2]);
    if (!Array.isArray(value)) return line;
    return value.map((item) => (item === '' ? '' : `${m[1]}${item}`)).join('\n');
  }).join('\n');
  const rendered = expanded.replace(PLACEHOLDER_RE, (_, name) => {
    const { sub, value } = valueOf(name);
    if (Array.isArray(value)) {
      throw new PipelineError(`${label}: placeholder {{${name}}}: a list renders one line per item, so it stands alone on its line`);
    }
    if (sub.context === 'shell') return shellQuote(value);
    return value;
  });
  if (rendered.includes('{{')) {
    throw new PipelineError(`${label}: unresolved "{{" left after rendering`);
  }
  // Placement was checked on the template, so a substituted value must not
  // change which text is in which code block: a value line that opens or
  // closes a fence (a list item "```bash") would put the next value, read as
  // markdown, into a shell block (Codex review of PC2a2).
  if (JSON.stringify(fenceLines(rendered)) !== JSON.stringify(fenceLines(text))) {
    throw new PipelineError(`${label}: a substituted value opens or closes a code fence`);
  }
  return rendered;
}

/** The fence marker lines of a text, in order (a placeholder never sits on one). */
function fenceLines(text) {
  return text.split('\n').map((l) => l.trim()).filter((l) => /^(`{3,}|~{3,})/.test(l));
}

const PLACE_TEXT = {
  prose: 'in prose, outside a shell block',
  fence: 'in a code block that is not shell',
  'shell-single': "inside '…'",
  'shell-ansi': "inside $'…'",
  'shell-arith': 'inside an arithmetic expansion',
  'shell-escaped': 'right after a backslash',
  'shell-double': 'inside "…"',
  'shell-param': 'inside ${…}',
  'shell-backtick': 'inside backticks',
  'shell-comment': 'in a shell comment',
  'shell-heredoc': 'in a heredoc',
};
