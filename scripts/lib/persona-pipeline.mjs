export function validateLedger(ledger, personas) {
  const where = 'owned.json';
  if (!isPlainObject(ledger)) fail(where, 'is not an object');
  onlyKeys(ledger, ['schema', 'note', 'owned'], where);
  if (ledger.schema !== OWNED_SCHEMA) {
    fail(where, `schema is ${JSON.stringify(ledger.schema)}, expected ${JSON.stringify(OWNED_SCHEMA)}`);
  }
  if (!isPlainObject(ledger.owned)) fail(`${where}.owned`, 'must be an object');
  for (const [persona, paths] of Object.entries(ledger.owned)) {
    if (!PERSONA_RE.test(persona)) fail(`${where}.owned`, `invalid persona ${JSON.stringify(persona)}`);
    stringList(paths, `${where}.owned.${persona}`);
    for (const p of paths) {
      const reason = unsafePathReason(p);
      if (reason) fail(`${where}.owned.${persona}`, `${reason}: ${JSON.stringify(p)}`);
    }
  }
  void personas;
  return ledger;
}

export function renderLedger(owned) {
  const sorted = {};
  for (const persona of Object.keys(owned).sort()) {
    const paths = [...new Set(owned[persona])].sort();
    if (paths.length > 0) sorted[persona] = paths;
  }
  return `${JSON.stringify({
    schema: OWNED_SCHEMA,
    note: `Every plugin path persona-pipeline has generated, per persona. Written by ${WRITE_COMMAND}; do not edit.`,
    owned: sorted,
  }, null, 2)}\n`;
}

